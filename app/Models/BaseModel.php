<?php

declare(strict_types=1);

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Str;

/**
 * The base every domain model extends.
 *
 * Three rules the migrations depend on (01-STARTER-PACK.md §6.6):
 *
 *  1. **ULID char(26) primary keys.** The source used cuid() on Postgres heap
 *     tables, which did not care about key locality. InnoDB clusters on the
 *     primary key, so a random 25-char key page-splits on every insert.
 *  2. **`$dateFormat = 'Y-m-d H:i:s.v'`.** Every timestamp column is
 *     DATETIME(3), and Eloquent must WRITE the milliseconds the column
 *     declares — punch pairing orders by `logged_at` and task threads by
 *     `(task_id, created_at)`, so collapsing to whole seconds silently
 *     reorders a punch pair.
 *  3. **Mint an id only when one is absent.** New seeded and user-created
 *     domain rows share this generator; existing identifiers remain stable.
 *
 * Timestamps, across the whole model layer:
 *
 *  - The source has `created_at DateTime @default(now())` on every table and
 *    `updated_at` on exactly one (`attendance_remarks`). The migrations add a
 *    nullable `updated_at DATETIME(3)` to the mutable tables, and those models
 *    run Eloquent's full timestamp handling.
 *  - Append-only tables get no `updated_at` column: `payslips`, `task_comments`,
 *    `project_task_files`, `audit_logs` and `payroll_finalization_snapshots`. Those models
 *    declare `public const UPDATED_AT = null;` rather than
 *    `$timestamps = false`, which keeps Eloquent filling `created_at` on
 *    insert — the literal port of `@default(now())` — while never emitting an
 *    UPDATE for a column the table does not have. `$timestamps = false` would
 *    have left `created_at` NULL on a NOT NULL column instead.
 *  - `Shift` and `RoleModuleGrant` have neither column and so are genuinely
 *    `$timestamps = false`.
 *  - `AttendanceLog` has neither, but has `logged_at DateTime @default(now())`,
 *    so it maps `CREATED_AT` onto `logged_at`.
 *
 * Money is cast to `'float'`, never `decimal:2` — `decimal:2` returns a PHP
 * *string*, which is the exact defect `src/lib/api/respond.ts:5-8` exists to
 * fix (`peso("31000")` renders $NaN and every total concatenates). DECIMAL(n,2)
 * stays the storage type; float is the compute type. Both are deliberate.
 */
abstract class BaseModel extends Model
{
    /** ULIDs are supplied, never generated by the database. */
    public $incrementing = false;

    /** @var string */
    protected $keyType = 'string';

    /** DATETIME(3) — Eloquent must WRITE the milliseconds the column declares. */
    protected $dateFormat = 'Y-m-d H:i:s.v';

    /**
     * Generate a ULID for new rows without replacing imported identifiers.
     *
     * A subclass that needs its own model events must call `parent::booted()`.
     */
    protected static function booted(): void
    {
        static::creating(static function (BaseModel $model): void {
            $key = $model->getKey();

            if ($key === null || $key === '') {
                $model->setAttribute($model->getKeyName(), (string) Str::ulid());
            }
        });
    }
}
